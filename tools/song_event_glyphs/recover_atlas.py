#!/usr/bin/env python3
"""Rebuild the song marker atlas from the approved flattened HD symbol sheet."""

import argparse
import base64
import hashlib
import io
from pathlib import Path
import re
import textwrap

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont


ROOT = Path(__file__).resolve().parents[2]
SHEET_SHA256 = "d38c030b68af30bdb7cef34b0b4f337ff3545f830f3aba76f1c19287b7e5e085"
FONT_SHA256 = "57f73e11f51999432bf7ab22ce55b6f945d5eca1bf824404cfa9ec2e3718c84e"
MATTE = (28, 31, 34)
ICON_EXTENT = 80
REGION_PADDING = 4
ATLAS_WIDTH = 1024


def pinned_input(path, expected_hash):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise ValueError(f"Unexpected input revision for {path}")
    return io.BytesIO(data)


def song_labels():
    songs = (ROOT / "combo/rando/SongEvents.h").read_text()
    labels = re.search(r"SongLabels\[\]\s*=\s*\{([^}]+)\}", songs)
    if labels is None:
        raise ValueError("Cannot locate SongLabels")
    return [label.replace("'", "’") for label in re.findall(r'"([^"]+)"', labels[1])]


def unmatte(cell):
    background = np.asarray(MATTE, dtype=np.float32)
    delta = np.asarray(cell, dtype=np.float32) - background
    distance = np.max(np.abs(delta), axis=2)
    support = distance > 0
    interior = np.asarray(Image.fromarray(support.astype(np.uint8)).filter(ImageFilter.MinFilter(3)))
    local_max = np.asarray(Image.fromarray(distance.astype(np.uint8)).filter(ImageFilter.MaxFilter(5)))

    # The original alpha was flattened. Preserve opaque interiors and estimate
    # partial edge coverage from the adjacent colors, bounded by the RGB gamut.
    alpha = np.maximum(
        distance / np.maximum(local_max, 1),
        np.max(np.maximum(delta / (255 - background), -delta / background), axis=2),
    )
    alpha[interior != 0] = 1
    rgb = background + delta / np.maximum(alpha[:, :, None], 1 / 255)
    rgb[~support] = 0
    rgba = np.dstack((rgb, 255 * alpha)).clip(0, 255).round().astype(np.uint8)
    image = Image.fromarray(rgba)
    bounds = image.getbbox()
    if bounds is None:
        raise ValueError("Empty symbol cell")
    image = image.crop(bounds)
    image.thumbnail((ICON_EXTENT, ICON_EXTENT), Image.Resampling.LANCZOS)
    return image


def make_label(label, font):
    stroke = 4
    left, top, right, bottom = font.getbbox(label, stroke_width=stroke)
    image = Image.new("RGBA", (right - left, bottom - top))
    ImageDraw.Draw(image).text(
        (-left, -top), label, font=font, fill=(255, 250, 235, 255),
        stroke_width=stroke, stroke_fill=(21, 20, 25, 255),
    )
    return image


def make_glint(icon):
    glint = Image.new("RGBA", icon.size, "white")
    glint.putalpha(icon.getchannel("A"))
    return glint


def pack(regions):
    x = y = REGION_PADDING
    row_height = 0
    packed = []
    for group in regions:
        group_regions = []
        for image in group:
            width, height = image.size
            if x + width + REGION_PADDING > ATLAS_WIDTH:
                x = REGION_PADDING
                y += row_height + REGION_PADDING
                row_height = 0
            group_regions.append((x, y, width, height))
            x += width + REGION_PADDING
            row_height = max(row_height, height)
        packed.append(group_regions)

    atlas = Image.new("RGBA", (ATLAS_WIDTH, y + row_height + REGION_PADDING))
    for group, group_regions in zip(regions, packed, strict=True):
        for image, (x, y, width, height) in zip(group, group_regions, strict=True):
            atlas.paste(image, (x, y))
    return atlas, packed


def write_data(atlas, regions, png):
    lines = [
        "// Generated by tools/song_event_glyphs/recover_atlas.py.",
        "// Recovered from the approved flattened HD sheet. Coordinates are 2x display pixels.",
        f"inline constexpr int kAtlasWidth = {atlas.width};",
        f"inline constexpr int kAtlasHeight = {atlas.height};",
    ]
    for name, group in zip(("Icon", "Label", "Glint"), regions, strict=True):
        lines.append(f"inline constexpr Region k{name}Regions[] = {{")
        lines.extend(f"    {{ {x}, {y}, {width}, {height} }}," for x, y, width, height in group)
        lines.append("};")
    lines.append("inline constexpr std::string_view kEncodedPng[] = {")
    lines.extend(f'    "{chunk}",' for chunk in textwrap.wrap(base64.b64encode(png).decode("ascii"), 96))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sheet", type=Path, help="ComboShip_Song_Symbols_HD_Preview.png")
    parser.add_argument("--font", type=Path, default=Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"))
    parser.add_argument("--output", type=Path, default=ROOT / "combo/hud/SongEventGlyphAtlasData.inc")
    parser.add_argument("--preview", type=Path, help="Optional decoded atlas for local inspection")
    args = parser.parse_args()

    sheet = Image.open(pinned_input(args.sheet, SHEET_SHA256)).convert("RGB")
    font = ImageFont.truetype(pinned_input(args.font, FONT_SHA256), 32)
    icons = [
        unmatte(sheet.crop((288 * column, top, 288 * (column + 1), top + 274)))
        for top in (96, 415, 735, 1055)
        for column in range(5)
    ]
    labels = [make_label(label, font) for label in song_labels()]
    if len(labels) != len(icons):
        raise ValueError("Song labels and approved sheet membership differ")

    atlas, regions = pack((icons, labels, [make_glint(icon) for icon in icons]))
    buffer = io.BytesIO()
    atlas.save(buffer, format="PNG", optimize=True)
    png = buffer.getvalue()
    args.output.write_text(write_data(atlas, regions, png))
    if args.preview:
        args.preview.write_bytes(png)


if __name__ == "__main__":
    main()
