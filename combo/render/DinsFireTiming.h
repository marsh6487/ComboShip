/* Shared native timing. Literal base values are also read by the asset recipe. */
#ifndef COMBO_DINS_FIRE_TIMING_H
#define COMBO_DINS_FIRE_TIMING_H

#define CW_DINS_NATIVE_RATE 20
#define CW_DINS_NATIVE_CHARGE_TICKS 12
#define CW_DINS_NATIVE_STRIKE_TICKS 9
#define CW_DINS_NATIVE_RECOVERY_TICKS 6
#define CW_DINS_NATIVE_RELEASE_FRAME 30.0f
#define CW_DINS_NATIVE_GROW_TICKS 8
#define CW_DINS_NATIVE_INTERACTION_TICKS 120
#define CW_DINS_NATIVE_FADE_TICKS 12
#define CW_DINS_NATIVE_DAMAGE_HOLD_TICKS 32

/* Six seconds for movement/equipment/aiming after recovery, before burnout.
 * The added utility hold does not prolong the original strong damage ramp. */
#define CW_DINS_NATIVE_FADE_START_FRAME (CW_DINS_NATIVE_RECOVERY_TICKS + CW_DINS_NATIVE_INTERACTION_TICKS)
#define CW_DINS_NATIVE_HOLD_TICKS (CW_DINS_NATIVE_FADE_START_FRAME - CW_DINS_NATIVE_GROW_TICKS)
#define CW_DINS_NATIVE_FIRE_TICKS (CW_DINS_NATIVE_FADE_START_FRAME + CW_DINS_NATIVE_FADE_TICKS)
#define CW_DINS_NATIVE_FIRE_START_TIME \
    ((CW_DINS_NATIVE_CHARGE_TICKS + CW_DINS_NATIVE_STRIKE_TICKS) / (float)CW_DINS_NATIVE_RATE)
#define CW_DINS_NATIVE_FADE_AGE (CW_DINS_NATIVE_FADE_START_FRAME / (float)CW_DINS_NATIVE_RATE)
#define CW_DINS_NATIVE_FADE_TIME (CW_DINS_NATIVE_FIRE_START_TIME + CW_DINS_NATIVE_FADE_AGE)
#define CW_DINS_NATIVE_END_TIME \
    (CW_DINS_NATIVE_FIRE_START_TIME + CW_DINS_NATIVE_FIRE_TICKS / (float)CW_DINS_NATIVE_RATE)

#endif
